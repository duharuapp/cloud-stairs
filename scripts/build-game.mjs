// Packs game/index.html into src/game/html.ts for the app's WebView: three.js and the Jua font go inline,
// so the game runs offline and loads nothing from the internet. Run after every change to game/index.html
// (metro.config.js also runs it before each bundle).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);

const THREE_TAG = '<script src="https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js"></script>';
const FONT_TAGS = /<link rel="preconnect" href="https:\/\/fonts\.googleapis\.com">\s*<link rel="stylesheet" href="https:\/\/fonts\.googleapis\.com\/css2\?family=Jua[^"]*">/;

export async function buildGame() {
  let html = readFileSync(join(root, 'game/index.html'), 'utf8');
  if (!html.includes(THREE_TAG) || !FONT_TAGS.test(html)) throw new Error('game/index.html: three.js or font tag changed; update scripts/build-game.mjs');

  const three = readFileSync(require.resolve('three/build/three.min.js'), 'utf8');
  html = html.replace(THREE_TAG, () => '<script>' + three.replace(/<\/script/gi, '<\\/script') + '</script>');

  // Only the letters the game shows: ASCII, a few symbols, and every Hangul syllable in the page.
  const ttf = readFileSync(require.resolve('@expo-google-fonts/jua/400Regular/Jua_400Regular.ttf'));
  const hangul = [...new Set(html.match(/[가-힣]/g) ?? [])].join('');
  let ascii = '';
  for (let c = 32; c < 127; c++) ascii += String.fromCharCode(c);
  const font = await subsetFont(ttf, ascii + '×₩¥$€£·…' + hangul, { targetFormat: 'woff2' });
  const face = `<style>@font-face{font-family:"Jua";src:url(data:font/woff2;base64,${font.toString('base64')}) format("woff2");font-display:block}</style>`;
  html = html.replace(FONT_TAGS, () => face);

  mkdirSync(join(root, 'src/game'), { recursive: true });
  writeFileSync(
    join(root, 'src/game/html.ts'),
    '// Generated by scripts/build-game.mjs from game/index.html. Do not edit.\nexport default ' + JSON.stringify(html) + ';\n',
  );
  return html.length;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const n = await buildGame();
  console.log(`src/game/html.ts: ${(n / 1024).toFixed(0)} KB`);
}
